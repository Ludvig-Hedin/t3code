// ── Import Execute Route ──────────────────────────────────────────────────────

/**
 * Wraps in Layer.unwrap so OrchestrationEngineService is available via
 * closure inside the route handler.
 *
 * NOTE: We intentionally bypass normalizeDispatchCommand here. That helper
 * needs WorkspacePaths / FileSystem / ServerConfig which are not provided in
 * this layer's context. For the import flow the workspaceRoot is a resolved,
 * already-validated path from PROVIDER_HISTORY_CANDIDATES so normalisation
 * is not required.
 */
export const importExecuteRouteLayer = Layer.unwrap(
  Effect.gen(function* () {
    const engineOption = yield* Effect.serviceOption(OrchestrationEngineService);

    // Build the set of allowed history roots once so we can validate each
    // request's historyPath against it (defence-in-depth on a local server).
    const home = os.homedir();
    const allowedRoots = new Set<string>(
      Object.values(PROVIDER_HISTORY_CANDIDATES).flatMap((fn) => fn(home).filter(Boolean)),
    );

    const isAllowedPath = (p: string) => {
      for (const root of allowedRoots) {
        if (p === root || p.startsWith(root + nodePath.sep)) return true;
      }
      return false;
    };

    return HttpRouter.add(
      "POST",
      "/api/setup/import/execute",
      Effect.gen(function* () {
        const denied = yield* authorizeSetupRequest;
        if (Option.isSome(denied)) return denied.value;
        if (Option.isNone(engineOption)) {
          return HttpServerResponse.setHeaders(
            HttpServerResponse.jsonUnsafe(
              { error: "Orchestration engine unavailable" },
              { status: 503 },
            ),
            SETUP_CORS_HEADERS,
          );
        }
        const engine = engineOption.value;
        // Parse request body — return 400 explicitly instead of silently
        // returning an empty selection list, so callers see why their request failed.
        const bodyResult = yield* HttpServerRequest.schemaBodyJson(ImportRequest).pipe(
          Effect.result,
        );
        if (bodyResult._tag === "Failure") {
          return HttpServerResponse.setHeaders(
            HttpServerResponse.jsonUnsafe(
              { error: "Invalid request body", detail: String(bodyResult.failure) },
              { status: 400 },
            ),
            SETUP_CORS_HEADERS,
          );
        }
        const body = bodyResult.success;

        let importedProjectCount = 0;
        let importedThreadCount = 0;
        const errors: string[] = [];

        for (const selection of body.selections) {
          // Security: only read from paths within known provider history roots
          if (!isAllowedPath(selection.historyPath)) {
            errors.push(`Skipped "${selection.projectName}": path not within an allowed root.`);
            continue;
          }

          // Validate projectPath: must be absolute, fully resolved (no `..`),
          // not point at root or a system directory. Without this the server
          // would accept e.g. "/", "/etc", or arbitrary paths supplied by a
          // local attacker and create a project bound to that workspace.
          const rawProjectPath = selection.projectPath;
          const resolvedProjectPath = nodePath.resolve(rawProjectPath);
          const isAbsolute = nodePath.isAbsolute(rawProjectPath);
          const isNormalized = rawProjectPath === resolvedProjectPath;
          const isSensitiveRoot =
            resolvedProjectPath === "/" ||
            resolvedProjectPath === "/etc" ||
            resolvedProjectPath === "/usr" ||
            resolvedProjectPath === "/bin" ||
            resolvedProjectPath === "/sbin" ||
            resolvedProjectPath === "/var" ||
            resolvedProjectPath === os.homedir();
          if (!isAbsolute || !isNormalized || isSensitiveRoot) {
            errors.push(
              `Skipped "${selection.projectName}": invalid project path "${rawProjectPath}".`,
            );
            continue;
          }
          const projectPathStat = yield* Effect.tryPromise(() =>
            nodeFs.stat(resolvedProjectPath),
          ).pipe(Effect.result);
          if (projectPathStat._tag === "Failure" || !projectPathStat.success.isDirectory()) {
            errors.push(`Skipped "${selection.projectName}": project path is not a directory.`);
            continue;
          }

          const createdAt = new Date().toISOString();
          const title = TrimmedNonEmptyString.makeUnsafe(
            selection.projectName.slice(0, 200) || "Imported Project",
          );
          const workspaceRoot = TrimmedNonEmptyString.makeUnsafe(resolvedProjectPath);

          // C6: dedupe project by workspaceRoot. Re-running import previously
          // generated fresh UUIDs every time, doubling the sidebar on every
          // run. Look up an existing non-deleted project first and reuse it.
          const readModelBeforeProject = yield* engine.getReadModel();
          const existingProject = readModelBeforeProject.projects.find(
            (entry) => entry.workspaceRoot === resolvedProjectPath && entry.deletedAt === null,
          );

          let projectId: ProjectId;
          if (existingProject) {
            projectId = existingProject.id;
            // No project.create dispatch — already exists.
          } else {
            projectId = ProjectId.makeUnsafe(crypto.randomUUID());
            const projectCommand: OrchestrationCommand = {
              type: "project.create",
              commandId: CommandId.makeUnsafe(`import:project:${crypto.randomUUID()}`),
              projectId,
              title,
              workspaceRoot,
              createdAt,
            };

            const projectResult = yield* engine.dispatch(projectCommand).pipe(
              Effect.catch((err) => {
                errors.push(`Dispatch project "${selection.projectName}": ${String(err)}`);
                return Effect.succeed({ sequence: -1 });
              }),
            );
            if (projectResult.sequence === -1) {
              continue;
            }
            importedProjectCount++;
          }

          // C6: pre-load existing thread titles for this project so we can
          // skip imports that would duplicate. Imperfect — import payloads
          // don't carry a stable (provider, sessionId) identity in the read
          // model — but title-based dedupe blocks the disaster case where a
          // re-run doubles every imported thread.
          const readModelAfterProject = yield* engine.getReadModel();
          const existingTitlesForProject = new Set(
            readModelAfterProject.threads
              .filter((entry) => entry.projectId === projectId && entry.deletedAt === null)
              .map((entry) => entry.title.trim().toLowerCase()),
          );

          // ── Discover threads for this project ─────────────────────────────
          // For smart providers (codex, claudeAgent) this returns real sessions
          // with parsed titles. For generic providers it falls back to a flat
          // directory listing where filenames become titles.
          const sessions = yield* Effect.tryPromise(() =>
            enumerateSessionsForSelection(
              selection.provider,
              selection.historyPath,
              selection.projectPath,
            ),
          ).pipe(Effect.orElseSucceed(() => [] as DiscoveredSession[]));

          type ThreadToCreate = { title: string };
          const threadsToCreate: ThreadToCreate[] = [];

          if (sessions.length > 0) {
            // Sort newest-first so the most recent CLI conversations appear at the top.
            sessions.sort((a, b) => b.modifiedAtMs - a.modifiedAtMs);
            for (const session of sessions.slice(0, 100)) {
              const rawTitle = session.title ?? session.sessionId;
              threadsToCreate.push({
                title: rawTitle.slice(0, 80).trim() || "Imported conversation",
              });
            }
          } else {
            // Generic-provider fallback: enumerate files directly.
            const files = yield* Effect.tryPromise(() =>
              nodeFs
                .readdir(selection.historyPath)
                .then((entries) =>
                  entries
                    .filter((f) => f.endsWith(".json") || f.endsWith(".jsonl") || f.endsWith(".md"))
                    .slice(0, 50),
                ),
            ).pipe(Effect.orElseSucceed(() => [] as string[]));

            const fallback =
              files.length > 0
                ? files
                : [`${selection.projectName} (imported)`.slice(0, 80).trim()];

            for (const file of fallback) {
              const rawTitle =
                file
                  .replace(/\.(json|jsonl|md)$/, "")
                  .replace(/[_-]/g, " ")
                  .trim()
                  .slice(0, 80) || "Imported conversation";
              threadsToCreate.push({ title: rawTitle });
            }
          }

          for (const { title: rawTitle } of threadsToCreate) {
            // C6: skip threads whose title already exists for this project
            // (case-insensitive, trimmed) — prevents re-imports from doubling.
            const titleKey = rawTitle.trim().toLowerCase();
            if (existingTitlesForProject.has(titleKey)) {
              continue;
            }

            const threadId = ThreadId.makeUnsafe(crypto.randomUUID());
            const threadTitle = TrimmedNonEmptyString.makeUnsafe(rawTitle);

            const threadCommand: OrchestrationCommand = {
              type: "thread.create",
              commandId: CommandId.makeUnsafe(`import:thread:${crypto.randomUUID()}`),
              threadId,
              projectId,
              title: threadTitle,
              // manifest = smart-router: routes to cheapest capable model automatically
              modelSelection: {
                provider: "manifest",
                model: TrimmedNonEmptyString.makeUnsafe("auto"),
              },
              runtimeMode: DEFAULT_RUNTIME_MODE,
              interactionMode: DEFAULT_PROVIDER_INTERACTION_MODE,
              branch: null,
              worktreePath: null,
              createdAt,
            };

            const threadResult = yield* engine.dispatch(threadCommand).pipe(
              Effect.catch((err) => {
                errors.push(`Dispatch thread "${rawTitle}": ${String(err)}`);
                return Effect.succeed({ sequence: -1 });
              }),
            );
            if (threadResult.sequence !== -1) {
              importedThreadCount++;
              existingTitlesForProject.add(titleKey);
            }
          }
        }

        return HttpServerResponse.setHeaders(
          HttpServerResponse.jsonUnsafe({
            importedProjectCount,
            importedThreadCount,
            errors,
          }),
          SETUP_CORS_HEADERS,
        );
      }),
    );
  }),
);
